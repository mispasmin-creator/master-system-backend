const { prisma } = require('../../config/db');

const num = (v) => {
  const n = parseFloat(v);
  return Number.isFinite(n) ? n : null;
};

// @desc    List lifts pending full-kitting + already-kitted history
// @route   GET /api/purchase/fullkitting/data
// @access  Public
const listData = async (req, res, next) => {
  try {
    const lifts = await prisma.purchaseLift.findMany({
      orderBy: { timestamp: 'desc' },
      include: {
        receipt: true,
        fullkitting: true,
        mismatches: { include: { aaBillEntries: true } },
        indent: { include: { generatePo: true } },
      },
    });

    const data = lifts
      .map((l) => {
        const mismatch = l.mismatches?.[0] || null;
        const isDone = Boolean(l.fullkitting);
        // Mirrors the reference's Actual6 gate: only pending once the
        // Accounts-Audit chain's Bill Entry stage has been marked Done.
        const billEntryDone = (l.mismatches || []).some((m) =>
          (m.aaBillEntries || []).some((be) => be.status === 'Done'),
        );
        if (!isDone && !billEntryDone) return null;

        const fk = l.fullkitting;
        const liftRow = {
          Timestamp: l.timestamp ? l.timestamp.toISOString() : '',
          Qty: l.qty != null ? String(l.qty) : '',
          'Lifting Qty': l.liftingQty != null ? String(l.liftingQty) : '',
          'Area lifting': l.areaLifting || '',
          'Bill No.': l.billNo || '',
          Type: l.type || '',
          Rate: l.rate != null ? String(l.rate) : '',
          'Truck Qty': l.truckQty != null ? String(l.truckQty) : '',
          'Bill Image': l.billImage || '',
          'Image Of Weight Slip': l.receipt?.imageOfWeightSlip || '',
          'Qty Difference Status': mismatch?.qtyDiffStatus || '',
          'Driver No.': l.driverNo || '',
          'Lead Time To Reach Factory (days)': l.leadTimeToReachFactory != null ? String(l.leadTimeToReachFactory) : '',
          'Date Of Receiving': l.receipt?.dateOfReceiving ? l.receipt.dateOfReceiving.toISOString() : '',
          'Total Bill Quantity': l.receipt?.totalBillQuantity != null ? String(l.receipt.totalBillQuantity) : '',
          'Actual Quantity': l.receipt?.actualQuantity != null ? String(l.receipt.actualQuantity) : '',
          Moisture: l.receipt?.moisture || '',
        };
        const poRow = {
          Timestamp: l.indent?.timestamp ? l.indent.timestamp.toISOString() : '',
          'Firm Name': l.indent?.firmName || '',
          'Generated By': l.indent?.generatedBy || '',
          Quantity: l.indent?.quantity != null ? String(l.indent.quantity) : '',
          Rate: l.indent?.generatePo?.rate != null ? String(l.indent.generatePo.rate) : '',
          'Total Quantity': l.indent?.generatePo?.totalQuantity != null ? String(l.indent.generatePo.totalQuantity) : '',
          'Total Amount': l.indent?.generatePo?.totalAmount != null ? String(l.indent.generatePo.totalAmount) : '',
          'PO Copy': l.indent?.generatePo?.poCopy || '',
        };

        return {
          id: `kitting-${l.id}`,
          originalId: l.id,
          fullkittingId: fk?.id,
          originalRow: liftRow,
          liftRow,
          poRow,
          firmName: l.firmName || '',
          liftNumber: l.liftNo || '',
          partyName: l.vendorName || '',
          productName: l.rawMaterialName || '',
          materialLoadDetails: fk?.materialLoadDetails || l.rawMaterialName || '',
          transporterName: fk?.transporterName || mismatch?.transporterName || mismatch?.transporter || l.transporterName || '',
          isPending: !isDone,
          isHistory: isDone,
          date: l.timestamp ? l.timestamp.toISOString() : '',
          qty: l.qty != null ? String(l.qty) : '',
          billingQty: l.liftingQty != null ? String(l.liftingQty) : (l.receipt?.totalBillQuantity != null ? String(l.receipt.totalBillQuantity) : ''),
          areaLifting: l.areaLifting || '',
          billNo: l.billNo || '',
          materialRate: l.rate != null ? String(l.rate) : '',
          additionalTruckQty: l.truckQty != null ? String(l.truckQty) : '',
          billImage: l.billImage || '',
          driverNo: l.driverNo || '',
          leadTime: l.leadTimeToReachFactory != null ? String(l.leadTimeToReachFactory) : '',
          indentNo: l.indentId != null ? String(l.indentId) : '',
          biltyNo: fk?.biltyNumber || l.biltyNo || '',
          biltyImage: fk?.biltyImage || l.biltyImage || '',
          transporterBillImage: fk?.transporterBillImage || null,
          fullkittingRemarks: fk?.fullkittingRemarks || '',
          typeOfRate: l.typeOfTransportingRate || '',
          transportingRate: l.transportingRate != null ? String(l.transportingRate) : '',
          transportRate: fk?.amount != null ? String(fk.amount) : '',
          rate: l.rate || 0,
          truckNo: fk?.vehicleNumber || l.truckNo || '',
          hasBilty: (fk?.biltyNumber || l.biltyNo) ? 'Yes' : 'No',
        };
      })
      .filter(Boolean);

    res.json({ success: true, data });
  } catch (error) {
    next(error);
  }
};

// @desc    Create a full-kitting record for a lift and sync transporter/bilty
//          info back onto its linked Mismatch row(s)
// @route   POST /api/purchase/fullkitting/submit
// @access  Private
const submitKitting = async (req, res, next) => {
  try {
    const {
      liftId,
      fmsName,
      status,
      transporterName,
      vehicleNumber,
      from,
      to,
      materialLoadDetails,
      biltyNumber,
      rateType,
      amount,
      biltyImage,
      transporterBillImage,
      fullkittingRemarks,
    } = req.body;

    const liftIdNum = Number(liftId);
    if (!Number.isFinite(liftIdNum)) {
      res.status(400);
      throw new Error('liftId is required');
    }

    const existing = await prisma.purchaseFullkitting.findUnique({ where: { liftId: liftIdNum } });
    if (existing) {
      res.status(400);
      throw new Error('Kitting already created for this lift');
    }

    const amountNum = num(amount);

    const fullkitting = await prisma.purchaseFullkitting.create({
      data: {
        liftId: liftIdNum,
        fmsName: fmsName || null,
        status: status || null,
        transporterName: transporterName || null,
        vehicleNumber: vehicleNumber || null,
        from: from || null,
        to: to || null,
        materialLoadDetails: materialLoadDetails || null,
        biltyNumber: biltyNumber || null,
        rateType: rateType || null,
        amount: amountNum,
        biltyImage: biltyImage || null,
        transporterBillImage: transporterBillImage || null,
        fullkittingRemarks: fullkittingRemarks || null,
        timestamp: new Date(),
      },
    });

    await prisma.purchaseMismatch.updateMany({
      where: { liftId: liftIdNum },
      data: {
        transporterName: transporterName || undefined,
        transporter: transporterName || undefined,
        truckNo: vehicleNumber || undefined,
        biltyNo: biltyNumber || undefined,
        biltyImage: biltyImage || undefined,
        totalFreight: amountNum ?? undefined,
      },
    });

    res.status(201).json({ success: true, data: { fullkittingId: fullkitting.id } });
  } catch (error) {
    next(error);
  }
};

// @desc    Bulk-edit already-kitted history rows
// @route   POST /api/purchase/fullkitting/bulk-update
// @access  Private
const bulkUpdate = async (req, res, next) => {
  try {
    const { updates } = req.body;
    if (!Array.isArray(updates) || updates.length === 0) {
      res.status(400);
      throw new Error('updates array is required');
    }

    await prisma.$transaction(
      updates.map((u) => {
        const data = {};
        if (u.transporterName !== undefined) data.transporterName = u.transporterName || null;
        if (u.truckNo !== undefined) data.vehicleNumber = u.truckNo || null;
        if (u.materialLoadDetails !== undefined) data.materialLoadDetails = u.materialLoadDetails || null;
        if (u.biltyNo !== undefined) data.biltyNumber = u.biltyNo || null;
        if (u.transportRate !== undefined) data.amount = u.transportRate === '' ? null : num(u.transportRate);
        if (u.fullkittingRemarks !== undefined) data.fullkittingRemarks = u.fullkittingRemarks || null;
        if (u.biltyImage !== undefined) data.biltyImage = u.biltyImage || null;
        if (u.transporterBillImage !== undefined) data.transporterBillImage = u.transporterBillImage || null;

        return prisma.purchaseFullkitting.update({ where: { id: Number(u.id) }, data });
      }),
    );

    res.json({ success: true });
  } catch (error) {
    next(error);
  }
};

module.exports = { listData, submitKitting, bulkUpdate };
